function chunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body), 0);
  return Buffer.concat([len, body, crc]);
}

export function writePng(opts: {
  width: number;
  height: number;
  lines: string[];
  seedByte: number;
  texts: Record<string, string>;
}): Buffer {
  const { width, height } = opts;
  const raw = Buffer.alloc((width * 3 + 1) * height);
  for (let y = 0; y < height; y++) {
    const rowStart = y * (width * 3 + 1);
    raw[rowStart] = 0;
    for (let x = 0; x < width; x++) {
      const p = rowStart + 1 + x * 3;
      const v = (x * 7 + y * 13 + opts.seedByte) % 23 < 2 ? 238 : 252;
      raw[p] = v; raw[p + 1] = v; raw[p + 2] = v - 4;
    }
  }
  const putPixel = (x: number, y: number, r: number, g: number, b: number) => {
    if (x < 0 || y < 0 || x >= width || y >= height) return;
    const p = y * (width * 3 + 1) + 1 + x * 3;
    raw[p] = r; raw[p + 1] = g; raw[p + 2] = b;
  };
  let cy = 10;
  for (const line of opts.lines) {
    let cx = 10;
    for (const ch of line.toUpperCase()) {
      const glyph = FONT[ch] ?? FONT[' ']!;
      for (let col = 0; col < 5; col++) {
        for (let row = 0; row < 7; row++) {
          if ((glyph[col]! >> row) & 1) {
            for (let sx = 0; sx < 2; sx++) for (let sy = 0; sy < 2; sy++) putPixel(cx + col * 2 + sx, cy + row * 2 + sy, 30, 30, 90);
          }
        }
      }
      cx += 12;
    }
    cy += 20;
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; ihdr[9] = 2;
  const parts: Buffer[] = [Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])];
  parts.push(chunk('IHDR', ihdr));
  for (const [k, v] of Object.entries(opts.texts)) {
    const itxt = Buffer.concat([
      Buffer.from(k, 'latin1'),
      Buffer.from([0, 0, 0]),
      Buffer.from([0]),
      Buffer.from(v, 'utf8'),
    ]);
    parts.push(chunk('iTXt', itxt));
  }
  parts.push(chunk('IDAT', deflateSync(raw, { level: 9 })));
  parts.push(chunk('IEND', Buffer.alloc(0)));
  return Buffer.concat(parts);
}
