export const HUMAN_ROLES = new Set([
  'JD_BUSINESS',
  'PROVIDER_BUSINESS',
  'PROVIDER_DATA',
  'PROVIDER_RECEIVABLE',
  'PROVIDER_INTEGRATION',
  'JD_INSTALLATION_REVIEW',
  'JD_RECONCILIATION',
  'JD_COORDINATION',
]);

export function isHumanRole(role: string): boolean {
  return HUMAN_ROLES.has(role);
}
